before(() => {
  runner = createTreeSitter();
  configuration = join(runner.directory, "highlight.json");
  capturePath = join(runner.directory, "captures.txt");
  writeFileSync(
    configuration,
    JSON.stringify({
      "parser-directories": [dirname(root)],
      theme: Object.fromEntries(
        captureNames.map((name, index) => [name, firstThemeColor + index]),
      ),
    }),
  );
  writeFileSync(capturePath, `${captureNames.join("\n")}\n`);
});
after(() => runner?.close());

function highlight(source, complete = true) {
  const path = join(runner.directory, "highlight.zsh");
  writeFileSync(path, source);
  if (complete) {
    const parsed = runner.run([
      "parse",
      "--cst",
      "--config-path",
      configuration,
      "--scope",
      language.scope,
      path,
    ]);
    assert.equal(parsed.status, 0, parsed.stdout + parsed.stderr);
    assert.doesNotMatch(parsed.stdout, /^[0-9: \t-]+•/m);
  }
  const result = runner.run([
    "highlight",
    "--check",
    "--captures-path",
    capturePath,
    "--config-path",
    configuration,
    "--html",
    "--layout",
    "fragment",
    "--style",
    "minimal",
    "--scope",
    language.scope,
    path,
  ]);
  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.doesNotMatch(result.stderr, /Non-standard highlight captures/);
  const start = result.stdout.indexOf("<pre><code>");
  const end = result.stdout.indexOf("</code></pre>");
  assert.ok(start >= 0 && end >= start, result.stdout);
  const content = result.stdout.slice(start + "<pre><code>".length, end);
  const stack = [];
  const captures = [];
  let rendered = "";
  for (const part of content.matchAll(
    /<span class='([^']*)'>|<[/]span>|([^<]+)/g,
  )) {
    if (part[1] !== undefined) stack.push(part[1].replaceAll(" ", "."));
    else if (part[0] === "</span>") assert.notEqual(stack.pop(), undefined);
    else {
      const text = part[2]
        .replaceAll("&lt;", "<")
        .replaceAll("&gt;", ">")
        .replaceAll("&quot;", '"')
        .replaceAll("&#39;", "'")
        .replaceAll("&amp;", "&");
      rendered += text;
      captures.push(...Array(Buffer.byteLength(text)).fill(stack.at(-1) ?? ""));
    }
  }
  assert.equal(stack.length, 0);
  assert.equal(rendered.replace(/\n$/, ""), source.replace(/\n$/, ""));
  return captures;
}


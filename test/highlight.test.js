for (const { name, parts } of cases) {
  test(name, () => {
    const source = parts.map(([text]) => text).join("");
    const expected = parts.flatMap(([text, capture = ""]) =>
      Array(Buffer.byteLength(text)).fill(capture),
    );
    const actual = highlight(source);
    for (const [byte, value] of Buffer.from(source).entries()) {
      if (value !== 10)
        assert.equal(actual[byte], expected[byte], `byte ${byte} in ${source}`);
    }
  });
}

test("incomplete input preserves source and never adds error captures", () => {
  for (const source of ["", "if true; then", 'print "unfinished', "print ${x"])
    for (const capture of highlight(source, false))
      assert.ok(capture === "" || captureNames.includes(capture));
});
